CREATE TABLE IF NOT EXISTS "user" (
  user_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_name            VARCHAR UNIQUE,
  user_password        VARCHAR,
  created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
  user_email           VARCHAR UNIQUE,
  is_verified          BOOLEAN NOT NULL DEFAULT false,
  verify_token         VARCHAR,
  verify_token_expires TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS book (
  book_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_name     VARCHAR,
  book_borrowed BIGINT REFERENCES "user"(user_id),
  book_status   BOOLEAN,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS loans (
  loan_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     BIGINT REFERENCES "user"(user_id),
  book_id     BIGINT REFERENCES book(book_id),
  borrowed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  return_at   TIMESTAMPTZ
);

