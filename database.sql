DO $$
DECLARE
  t record;
BEGIN
  FOR t IN SELECT * FROM (VALUES ('book', 'book_id'), ('loans', 'loan_id'), ('user', 'user_id')) AS v(tbl, col)
  LOOP
    IF EXISTS (
      SELECT 1 FROM information_schema.columns
      WHERE table_schema = 'public' AND table_name = t.tbl AND column_name = t.col
        AND is_identity = 'NO' AND column_default IS NULL
    ) THEN
      EXECUTE format('ALTER TABLE %I ALTER COLUMN %I ADD GENERATED BY DEFAULT AS IDENTITY', t.tbl, t.col);
      EXECUTE format('SELECT setval(pg_get_serial_sequence(%L, %L), COALESCE(MAX(%I), 0) + 1, false) FROM %I',
                     format('%I', t.tbl), t.col, t.col, t.tbl);
    END IF;
  END LOOP;
END $$;

